public class WhileVsFor {
    public static void main(String[] args) {
        
        // mostra os valores de 1 a 10

        // while
        int a = 1;
        while (a <= 10) {
            System.out.println(a);
            a++;
        }

        for (int b = 1; b <= 10; b++) {
            System.out.println(b);
        }
    
    }
}
